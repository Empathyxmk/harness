package net.yacy.grid.coverage;

public class DemoCoverage {
    // Simple methods for demo test coverage

    public int add(int a, int b) {
        return a + b;
    }

    public boolean isEven(int num) {
        return num % 2 == 0;
    }

    public int divide(int a, int b) {
        return a / b;
    }
}