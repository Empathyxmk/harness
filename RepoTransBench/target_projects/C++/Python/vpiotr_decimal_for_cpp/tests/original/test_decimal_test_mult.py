import pytest
from src.decimal.decimal import Decimal2, Decimal4, Decimal6, Decimal9

def test_decimal_multiply_prec():
    assert Decimal4("0.0001") * Decimal4("1.0000") == Decimal4("0.0001")
    assert Decimal4("0.0010") * Decimal4("1.1000") == Decimal4("0.0011")
    assert Decimal4("2.0100") * Decimal4("1.1000") == Decimal4("2.211")
    assert Decimal4("2.5010") * Decimal4("1.5000") == Decimal4("3.7515")
    assert Decimal4("-0.0001") * Decimal4("1.0000") == Decimal4("-0.0001")
    assert Decimal4("-0.0010") * Decimal4("1.1000") == Decimal4("-0.0011")
    assert Decimal4("-2.0100") * Decimal4("1.1000") == Decimal4("-2.211")
    assert Decimal4("-2.5010") * Decimal4("1.5000") == Decimal4("-3.7515")
    assert Decimal4("0.0001") * Decimal4("-1.0000") == Decimal4("-0.0001")
    assert Decimal4("0.0010") * Decimal4("-1.1000") == Decimal4("-0.0011")
    assert Decimal4("2.0100") * Decimal4("-1.1000") == Decimal4("-2.211")
    assert Decimal4("2.5010") * Decimal4("-1.5000") == Decimal4("-3.7515")
    assert Decimal4("-0.0001") * Decimal4("-1.0000") == Decimal4("0.0001")
    assert Decimal4("-0.0010") * Decimal4("-1.1000") == Decimal4("0.0011")
    assert Decimal4("-2.0100") * Decimal4("-1.1000") == Decimal4("2.211")
    assert Decimal4("-2.5010") * Decimal4("-1.5000") == Decimal4("3.7515")

    assert Decimal9("1.5") * Decimal9("2.1000") == Decimal9("3.15")
    assert Decimal9("1.000000005") * Decimal9("2") == Decimal9("2.000000010")
    assert Decimal9("1.80000001") * Decimal9("2") == Decimal9("3.600000020")
    assert Decimal9("1.80000001") * Decimal9("2") == Decimal9("3.600000020")

    assert Decimal6("35000.000005") * Decimal6("54123.654133") == Decimal6("1894327894.925618")

def test_decimal_multiply_int():
    assert Decimal4("0.0001") * 2 == Decimal4("0.0002")
    assert Decimal4("0.1001") * 3 == Decimal4("0.3003")
    assert Decimal4("1.1001") * 3 == Decimal4("3.3003")
    assert Decimal4("1.0001") * 3 == Decimal4("3.0003")
    assert Decimal4("1.0") * 3 == Decimal4("3.0")
    assert Decimal4("0.0001") * -2 == Decimal4("-0.0002")
    assert Decimal4("0.1001") * -3 == Decimal4("-0.3003")
    assert Decimal4("1.1001") * -3 == Decimal4("-3.3003")
    assert Decimal4("1.0001") * -3 == Decimal4("-3.0003")
    assert Decimal4("1.0") * -3 == Decimal4("-3.0")
    assert Decimal4("-0.0001") * 2 == Decimal4("-0.0002")
    assert Decimal4("-0.1001") * 3 == Decimal4("-0.3003")
    assert Decimal4("-1.1001") * 3 == Decimal4("-3.3003")
    assert Decimal4("-1.0001") * 3 == Decimal4("-3.0003")
    assert Decimal4("-1.0") * 3 == Decimal4("-3.0")
    assert Decimal4("-0.0001") * -2 == Decimal4("0.0002")
    assert Decimal4("-0.1001") * -3 == Decimal4("0.3003")
    assert Decimal4("-1.1001") * -3 == Decimal4("3.3003")
    assert Decimal4("-1.0001") * -3 == Decimal4("3.0003")
    assert Decimal4("-1.0") * -3 == Decimal4("3.0")