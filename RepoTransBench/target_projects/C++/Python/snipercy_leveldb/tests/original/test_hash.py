def test_hash_signed_unsigned_issue():
    import hashlib
    # Test simple hash properties
    def f(data):
        return int(hashlib.sha256(data).hexdigest(), 16)
    assert f(b"") != 0
    assert f(b"a") != f(b"foo")
    d1 = b"\x62"
    d2 = b"\xc3\x97"
    d3 = b"\xe2\x99\xa5"
    d4 = b"\xe1\x80\xb9\x32"
    d5 = bytes([
        0x01, 0xc0, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x14, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x04, 0x00,
        0x00, 0x00, 0x00, 0x14,
        0x00, 0x00, 0x00, 0x18,
        0x28, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x02, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
    ])
    hashes = [f(x) for x in [d1, d2, d3, d4, d5]]
    assert len(hashes) == 5
    assert len(set(hashes)) == 5