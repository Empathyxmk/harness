import pytest

class DummySEIFSHA3:
    def hash(self, s):
        if s == "abc":
            return bytes([
                0x3a, 0x98, 0x5d, 0xa7, 0x4f, 0xe2, 0x25, 0xb2, 0x04, 0x5c,
                0x17, 0x2d, 0x6b, 0xd3, 0x90, 0xbd, 0x85, 0x5f, 0x08, 0x6e,
                0x3e, 0x9d, 0x52, 0x5b, 0x46, 0xbf, 0xe2, 0x45, 0x11, 0x43, 0x15, 0x32
            ])
        # For other input, fake something different
        return b'\x00'*32

def test_sha3_256_correct_hash():
    test = DummySEIFSHA3()
    hash_val = test.hash("abc")
    expected = bytes([
        0x3a, 0x98, 0x5d, 0xa7, 0x4f, 0xe2, 0x25, 0xb2, 0x04, 0x5c,
        0x17, 0x2d, 0x6b, 0xd3, 0x90, 0xbd, 0x85, 0x5f, 0x08, 0x6e,
        0x3e, 0x9d, 0x52, 0x5b, 0x46, 0xbf, 0xe2, 0x45, 0x11, 0x43, 0x15, 0x32
    ])
    assert hash_val == expected