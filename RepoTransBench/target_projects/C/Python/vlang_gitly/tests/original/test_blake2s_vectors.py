@pytest.mark.skipif(not _HAS_BLAKE2S, reason="Python's hashlib does not have BLAKE2s support")
@pytest.mark.parametrize("tv", vectors)
def test_blake2s_vectors(tv):
    if tv.key:
        h = hashlib.blake2s(tv.input, key=tv.key)
    else:
        h = hashlib.blake2s(tv.input)
    digest = h.digest()
