from src.libfixmath_python.fix16 import fix16_from_dbl

def F16(x):
    # Accepts float and converts to fix16
    return fix16_from_dbl(float(x))

def test_macros():
    values = [
        (1.234, F16(1.234)), (0.0, F16(0.0)), (1.0, F16(1.0)), (-1.0, F16(-1.0)), 
        (1.5, F16(1.5)), (-1.5, F16(-1.5)), (0.0, F16(0.0)), (0.1, F16(0.1)), 
        (0.10, F16(0.10)), (0.1, F16(0.1)), (1.00001, F16(1.00001)), 
        (1.10000, F16(1.10000)), (25.133, F16(25.133)), (32767.0, F16(32767.0)), 
        (32767.00001, F16(32767.00001)), (32767.99999, F16(32767.99999)), (0.25, F16(0.25)), (0.99555, F16(0.99555)), 
        (0.99998, F16(0.99998)), (0.99999, F16(0.99999)), (-1.1, F16(-1.1)),
        (-25.133, F16(-25.133)), (-32767.00001, F16(-32767.00001)), (-32768.0, F16(-32768.0)),
        (0.2267, F16(0.2267)), (1.49887, F16(1.49887)), (0.27589, F16(0.27589)), (0.38393, F16(0.38393)), (0.8934, F16(0.8934))
    ]
    for val, expect in values:
        assert F16(val) == expect