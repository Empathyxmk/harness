import pytest
from src.tinyaes import aes

def phex(block):
    return ''.join(f'{x:02x}' for x in block)

def test_public_all_ff_cbc_encrypt_decrypt():
    key = [0xf0,0xe1,0xd2,0xc3,0xb4,0xa5,0x96,0x87,0x78,0x69,0x5a,0x4b,0x3c,0x2d,0x1e,0x0f]
    iv = [0x0f,0x1e,0x2d,0x3c,0x4b,0x5a,0x69,0x78,0x87,0x96,0xa5,0xb4,0xc3,0xd2,0xe1,0xf0]
    plain = [0xff]*16
    expected_enc = [0x49,0x96,0xa1,0xea,0x6d,0xd2,0xdd,0xf4,0xba,0x56,0x0b,0x20,0xaa,0x25,0xfa,0x37]
    buf = bytearray(plain)
    ctx = aes.AES_ctx()
    aes.AES_init_ctx_iv(ctx, key, iv)
    aes.AES_CBC_encrypt_buffer(ctx, buf, 16)
    assert list(buf) == expected_enc
    # decrypt should match original
    aes.AES_init_ctx_iv(ctx, key, iv)
    aes.AES_CBC_decrypt_buffer(ctx, buf, 16)
    assert list(buf) == plain

