def test_public_ctr_single_unique():
    key = [0x0f,0x15,0x71,0xc9,0x47,0xd9,0xe8,0x59,0x0c,0xb7,0xad,0xd6,0xaf,0x7f,0x67,0x98]
    iv  = [0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb]
    src = [0x01,0x23,0x45,0x67,0x89,0xab,0xcd,0xef,0x10,0x32,0x54,0x76,0x98,0xba,0xdc,0xfe]
    expected_enc = [0x2e,0xda,0x80,0x27,0xbb,0x3d,0x5a,0x7e,0x02,0x25,0x14,0x07,0x27,0x73,0xd2,0x92]
    ctx = aes.AES_ctx()
    buf = bytearray(src)
    aes.AES_init_ctx_iv(ctx, key, iv)
    aes.AES_CTR_xcrypt_buffer(ctx, buf, 16)
    assert list(buf) == expected_enc
    # decrypt round-trip
    aes.AES_init_ctx_iv(ctx, key, iv)
    aes.AES_CTR_xcrypt_buffer(ctx, buf, 16)
    assert list(buf) == src