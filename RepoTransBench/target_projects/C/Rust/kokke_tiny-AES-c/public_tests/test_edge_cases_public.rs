#[test]
fn public_test_all_ff_cbc_encrypt_decrypt() {
    let key = [
        0xf0,0xe1,0xd2,0xc3,0xb4,0xa5,0x96,0x87,0x78,0x69,0x5a,0x4b,0x3c,0x2d,0x1e,0x0f
    ];
    let iv = [
        0x0f,0x1e,0x2d,0x3c,0x4b,0x5a,0x69,0x78,0x87,0x96,0xa5,0xb4,0xc3,0xd2,0xe1,0xf0
    ];
    let plain = [0xffu8; 16];
    let enc_expected = [
        0x49,0x96,0xa1,0xea,0x6d,0xd2,0xdd,0xf4,0xba,0x56,0x0b,0x20,0xaa,0x25,0xfa,0x37
    ];
    let mut buf = plain;
    let mut ctx = AESCtx::new_iv(&key, &iv);
    aes_cbc_encrypt_buffer(&mut ctx, &mut buf);
    assert_eq!(&buf, &enc_expected, "public_test_all_ff_cbc_encrypt");
    // decrypt and check original
    let mut ctx = AESCtx::new_iv(&key, &iv);
    aes_cbc_decrypt_buffer(&mut ctx, &mut buf);
    assert_eq!(&buf, &plain, "public_test_all_ff_cbc_decrypt");
}

#[test]
fn public_test_ecb_alternate_bytes() {
    let key = [
        0x1b,0x2b,0x3c,0x4d,0x5e,0x6f,0x70,0x81,0x92,0xa3,0xb4,0xc5,0xd6,0xe7,0xf8,0x09
    ];
    let data = [0xaa,0x55,0xaa,0x55,0xaa,0x55,0xaa,0x55,0xaa,0x55,0xaa,0x55,0xaa,0x55,0xaa,0x55];
    let expected_enc = [0x42,0x02,0xae,0xe2,0x7e,0xfb,0xed,0x06,0x42,0x6b,0xcd,0xd0,0x71,0x4a,0x99,0xe0];
    let mut buf = data;
    // AES_ECB_encrypt(buf, key, 16);
    let mut ctx = AESCtx::new(&key);
    aes_ecb_encrypt(&mut ctx, &mut buf);
    assert_eq!(&buf, &expected_enc, "public_test_ecb_alternate_bytes_encrypt");
    aes_ecb_decrypt(&mut ctx, &mut buf);
    assert_eq!(&buf, &data, "public_test_ecb_alternate_bytes_decrypt");
}

#[test]
fn public_test_ctr_single_unique() {
    let key = [
        0x0f,0x15,0x71,0xc9,0x47,0xd9,0xe8,0x59,0x0c,0xb7,0xad,0xd6,0xaf,0x7f,0x67,0x98
    ];
    let iv = [
        0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb,0x00,0xfb
    ];
    let src = [0x01,0x23,0x45,0x67,0x89,0xab,0xcd,0xef,0x10,0x32,0x54,0x76,0x98,0xba,0xdc,0xfe];
    let expected_enc = [0x2e,0xda,0x80,0x27,0xbb,0x3d,0x5a,0x7e,0x02,0x25,0x14,0x07,0x27,0x73,0xd2,0x92];
    let mut buf = src;
    let mut ctx = AESCtx::new_iv(&key, &iv);
    aes_ctr_xcrypt_buffer(&mut ctx, &mut buf);
    assert_eq!(&buf, &expected_enc, "public_test_ctr_single_unique_encrypt");
    // decrypt back
    let mut ctx = AESCtx::new_iv(&key, &iv);
    aes_ctr_xcrypt_buffer(&mut ctx, &mut buf);
    assert_eq!(&buf, &src, "public_test_ctr_single_unique_decrypt");
}